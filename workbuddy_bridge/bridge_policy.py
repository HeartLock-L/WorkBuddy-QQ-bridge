def _needs_search(text: str) -> bool:
    """这条消息值不值得先联网查一下。

    2026-10-22 管理员问「有问题先搜索是不是失效了」——机制没坏，但旧判据只认
    「显式求搜」和「时间词 + 事实词」，像「V4 发布了吗」「某奖是谁」这种既没
    「今天」也没「搜一下」的问法全都漏搜，观感就跟没这功能一样。现在三条通路：
      1. 显式求搜（搜一下 / 查一下 / 有什么新闻…）→ 一律搜；
      2. 时间信号（今天 / 最近 / 20xx 年…）+ 事实词 → 搜；
      3. 问句标记（吗 / 多少 / 是谁…）+ 事实词 → 搜（补上没时间词的问法）。
    「怎么样 / 如何」不算问句标记：那是要观点，不是要事实，查了反而会被
    网页摘要带跑。

    Args:
        text: 群友这条消息的原文。

    Returns:
        是否应该在作答前检索一次。
    """
    t = (text or "").strip()
    if not t:
        return False
    low = t.lower()
    if any(k in low for k in _SEARCH_EXPLICIT):
        return True
    fact = _hit_words(low, _SEARCH_FACT)
    if not fact:
        return False
    if any(k in low for k in _SEARCH_TIME) or _SEARCH_YEAR.search(low):
        return True
    return any(k in low for k in _SEARCH_ASK)


def _clean_search_query(text: str) -> str:
    """把群聊原话收拾成能直接喂搜索引擎的查询串。

    去掉 @ 标记、链接和多余空白 —— 这些东西送给搜索引擎只会稀释关键词。
    """
    q = re.sub(r"\[At:\d+\]", " ", text or "")
    q = re.sub(r"@\S+", " ", q)
    q = re.sub(r"https?://\S+", " ", q)
    # 「搜一下」「帮我查查」这类是给机器人的指令，不是检索词，留着会稀释关键词
    for k in _SEARCH_EXPLICIT:
        q = q.replace(k, " ")
    q = re.sub(r"\s+", " ", q).strip()
    return q[:WEB_SEARCH_QUERY_MAX].strip()


def _web_search(query: str, limit: int = WEB_SEARCH_MAX_RESULTS) -> str:
    """用必应 RSS 拉一组公开结果，拼成给模型看的参考块。

    走 RSS 而不是抓 HTML：结构稳定、体积小、不用处理前端渲染。
    任何失败都返回空串 —— 搜不了就当没搜，绝不能因此拖死一轮回复。

    Args:
        query: 群友原话，内部会清洗成查询串。
        limit: 最多取几条结果。

    Returns:
        每行一条「标题：摘要」，或空串表示没搜到。
    """
    q = _clean_search_query(query)
    if not q:
        return ""
    url = "https://cn.bing.com/search?" + urllib.parse.urlencode(
        {"q": q, "format": "rss"}
    )
    req = urllib.request.Request(
        url,
        headers={
            "User-Agent": (
                "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                "AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"
            )
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=WEB_SEARCH_TIMEOUT) as resp:
            raw = resp.read()
    except Exception as exc:  # noqa: BLE001
        logger.warning(f"workbuddy_bridge: [联网] 检索失败: {type(exc).__name__}")
        return ""
    try:
        root = ET.fromstring(raw)
    except Exception as exc:  # noqa: BLE001
        logger.warning(f"workbuddy_bridge: [联网] 结果解析失败: {type(exc).__name__}")
        return ""
    lines: list[str] = []
    for item in root.iter("item"):
        title = re.sub(r"\s+", " ", (item.findtext("title") or "")).strip()
        desc = re.sub(r"\s+", " ", (item.findtext("description") or "")).strip()
        if not title:
            continue
        if len(desc) > WEB_SEARCH_DESC_MAX:
            desc = desc[:WEB_SEARCH_DESC_MAX] + "…"
        lines.append(f"- {title}：{desc}" if desc else f"- {title}")
        if len(lines) >= limit:
            break
    return "\n".join(lines)


