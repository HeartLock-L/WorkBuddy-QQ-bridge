def _is_paused() -> bool:
    """维护模式是否生效。flag 文件 mtime 超过 PAUSE_MAX_SEC 视为过期。

    只用 mtime 不用内容：双击 bat 就会重写这个空文件，零格式负担。
    """
    try:
        age = time.time() - PAUSE_FLAG.stat().st_mtime
    except OSError:
        return False  # 文件不存在 / 没权限 → 当正常态
    return age <= PAUSE_MAX_SEC


