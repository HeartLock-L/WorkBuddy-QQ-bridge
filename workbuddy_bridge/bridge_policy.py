def _is_at_me(event) -> bool:
    """消息链里是否 @ 了机器人本人（@全体也算）。"""
    me = str(event.get_self_id() or "").strip()
    for comp in event.get_messages() or []:
        if isinstance(comp, At):
            qq = str(getattr(comp, "qq", "") or "").strip()
            if qq == "all" or (me and qq == me):
                return True
    return False


